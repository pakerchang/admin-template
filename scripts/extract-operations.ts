/**
 * openapi.yaml → src/app/operations.gen.ts（`{ routes, permissions }`，spec §4.5 extract 列、§6.5、R15）。
 *
 *   pnpm exec tsx scripts/extract-operations.ts [--in openapi.yaml] [--out src/app/operations.gen.ts]
 *
 * gen 期斷言（M7 AC-2；任一失敗 exit 1、訊息指名 operation、不寫檔）：
 * 恰好一個 tag 且在 `tags` 清單、operationId 全檔唯一、有 `x-permission` 且為 `public` 或 `resource:action`
 * （不得 wildcard）、public ⇒ `security: []`（R21）、非 public ⇒ 不得 `security: []`（R27）。
 * 權限目錄比對不在這裡（R27：屬 build 期，`build()` 1.5.3）。
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

import { format, resolveConfig } from "prettier";
import { parse } from "yaml";

type TOperation = {
  operationId?: unknown;
  tags?: unknown;
  security?: unknown;
  "x-permission"?: unknown;
};
type TDocument = {
  tags?: { name: string }[];
  paths?: Record<string, Record<string, TOperation>>;
};
export type TExtracted = {
  routes: { method: string; path: string; operationId: string }[];
  permissions: Record<string, string>;
};

const METHODS = [
  "get",
  "put",
  "post",
  "delete",
  "patch",
  "options",
  "head",
  "trace",
];
const PERMISSION_RE = /^[a-z][a-z0-9-]*:[a-z][a-z0-9-]*$/;

export const extractOperations = (doc: TDocument): TExtracted => {
  const knownTags = new Set((doc.tags ?? []).map((tag) => tag.name));
  const errors: string[] = [];
  const routes: TExtracted["routes"] = [];
  const permissions: TExtracted["permissions"] = {};

  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const [key, op] of Object.entries(item)) {
      if (!METHODS.includes(key)) continue;
      const method = key.toUpperCase();
      const id =
        typeof op.operationId === "string" ? op.operationId : undefined;
      const name = `${id ?? "<missing operationId>"} (${method} ${path})`;
      const fail = (reason: string) => errors.push(`${name}: ${reason}`);

      if (!id) {
        fail("missing operationId");
        continue;
      }
      if (id in permissions) fail(`duplicate operationId "${id}"`);

      const tags = Array.isArray(op.tags) ? op.tags : [];
      if (tags.length !== 1)
        fail(`must have exactly one tag, got ${tags.length}`);
      for (const tag of tags)
        if (!knownTags.has(tag))
          fail(`tag "${tag}" is not in the top-level tags list`);

      const permission = op["x-permission"];
      const emptySecurity =
        Array.isArray(op.security) && op.security.length === 0;
      if (permission === undefined) fail("missing x-permission");
      else if (permission === "public") {
        if (!emptySecurity)
          fail('x-permission is "public" but security: [] is missing');
      } else if (
        typeof permission !== "string" ||
        !PERMISSION_RE.test(permission)
      )
        fail(
          `x-permission ${JSON.stringify(permission)} is neither "public" nor resource:action`
        );
      else if (emptySecurity)
        fail(`x-permission "${permission}" is not public but has security: []`);

      routes.push({
        method,
        path: path.replace(/\{([^}]+)\}/g, ":$1"),
        operationId: id,
      });
      permissions[id] = String(permission);
    }
  }

  if (errors.length) throw new Error(errors.join("\n"));
  return { routes, permissions };
};

export const renderOperationsModule = async (table: TExtracted, out: string) =>
  format(
    `// Generated by scripts/extract-operations.ts from openapi.yaml. Do not edit.
import type { TOperationTable } from "@/shared/permission";

export const operations: TOperationTable = ${JSON.stringify(table)};
`,
    { ...(await resolveConfig(out)), parser: "typescript" }
  );

const main = async () => {
  const { values } = parseArgs({
    options: {
      in: { type: "string", default: "openapi.yaml" },
      out: { type: "string", default: "src/app/operations.gen.ts" },
    },
  });
  const out = resolve(values.out);
  let table: TExtracted;
  try {
    table = extractOperations(parse(readFileSync(values.in, "utf8")));
  } catch (error) {
    console.error(
      `extract-operations: ${values.in} invalid\n${(error as Error).message}`
    );
    process.exit(1);
  }
  writeFileSync(out, await renderOperationsModule(table, out));
  console.log(
    `extract-operations: wrote ${table.routes.length} operations to ${out}`
  );
};

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
)
  await main();
