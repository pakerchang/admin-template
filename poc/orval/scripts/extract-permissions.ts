// 來源 (b) adapter：openapi.yaml 的 x-permission → generated/operations.gen.ts（中間格式 + 路由表）
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

import { fromOpenApi } from "../src/permissions";

const doc = parse(readFileSync(new URL("../openapi.yaml", import.meta.url), "utf8"));
const { routes, permissions } = fromOpenApi(doc);

writeFileSync(
  new URL("../generated/operations.gen.ts", import.meta.url),
  `// Generated by scripts/extract-permissions.ts. Do not edit.
import type { OperationPermissions, OperationRoute } from "../src/permissions";

export const operationRoutes: OperationRoute[] = ${JSON.stringify(routes, null, 2)};

export const operationPermissions: OperationPermissions = ${JSON.stringify(permissions, null, 2)};
`
);
console.log(`wrote ${routes.length} routes, ${Object.keys(permissions).length} permissions`);
