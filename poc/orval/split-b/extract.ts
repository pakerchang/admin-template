// B：單一 yaml → kernel 聚合檔 app/operations.gen.ts
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";
import { fromOpenApi } from "../src/permissions";

// argv[2] 可指定 yaml（測試用 fixture）；缺 x-permission 時 fromOpenApi throw → exit≠0，不寫檔
const { routes, permissions } = fromOpenApi(parse(readFileSync(process.argv[2] ?? new URL("../openapi.yaml", import.meta.url), "utf8")));
writeFileSync(
  new URL("./app/operations.gen.ts", import.meta.url),
  `// Generated by split-b/extract.ts. Do not edit.
import type { OperationPermissions, OperationRoute } from "../../src/permissions";
export const operationRoutes: OperationRoute[] = ${JSON.stringify(routes, null, 2)};
export const operationPermissions: OperationPermissions = ${JSON.stringify(permissions, null, 2)};
`
);
console.log(`B: wrote ${routes.length} routes`);
