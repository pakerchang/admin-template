// A：掃 modules/*/openapi.yaml → kernel 聚合檔 app/operations.gen.ts（跨片段的 operationId / route 撞名要自己擋）
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";
import { fromOpenApi, type OperationPermissions, type OperationRoute } from "../src/permissions";

const routes: OperationRoute[] = [];
const permissions: OperationPermissions = {};
for (const file of globSync("modules/*/openapi.yaml", { cwd: import.meta.dirname }).sort()) {
  const part = fromOpenApi(parse(readFileSync(new URL(file, import.meta.url), "utf8")));
  for (const r of part.routes) {
    const dup = routes.find((x) => x.operationId === r.operationId || (x.method === r.method && x.path === r.path));
    if (dup) throw new Error(`${file}: ${r.operationId} collides with ${dup.operationId}`);
    routes.push(r);
  }
  Object.assign(permissions, part.permissions);
}
writeFileSync(
  new URL("./app/operations.gen.ts", import.meta.url),
  `// Generated by split-a/extract.ts. Do not edit.
import type { OperationPermissions, OperationRoute } from "../../src/permissions";
export const operationRoutes: OperationRoute[] = ${JSON.stringify(routes, null, 2)};
export const operationPermissions: OperationPermissions = ${JSON.stringify(permissions, null, 2)};
`
);
console.log(`A: wrote ${routes.length} routes`);
